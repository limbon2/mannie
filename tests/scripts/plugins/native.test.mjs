// @ts-check
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';

import { parse } from 'smol-toml';

import { readRules } from '../../../scripts/plugins/lib/manifests.mjs';
import {
  codeOf,
  NATIVE_CALLS,
  NATIVE_CATEGORIES,
  nativeGrants,
  nativeSuppressions,
  pluginClippyConfiguration,
} from '../../../scripts/plugins/lib/native.mjs';

const root = fileURLToPath(new URL('../../../', import.meta.url));

/** A root configuration with one setting and one disallowed method of the core's own. */
const ROOT = `# The root's settings.
avoid-breaking-exported-api = false
disallowed-methods = [
  { path = "std::time::SystemTime::now", reason = "Code that depends on time takes the injected clock." },
]
`;

/**
 * A disallowed entry of a configuration.
 * @typedef {{ 'allow-invalid'?: boolean, path: string, reason: string }} Disallowed
 */

/**
 * The disallowed entries of a configuration.
 * @param {string} text
 * @param {'disallowed-methods' | 'disallowed-types'} key
 * @returns {Disallowed[]}
 */
function entries(text, key) {
  const parsed = JSON.parse(JSON.stringify(parse(text)));
  return parsed[key] ?? [];
}

/**
 * The paths of a configuration's disallowed entries.
 * @param {string} text
 * @param {'disallowed-methods' | 'disallowed-types'} key
 */
function paths(text, key) {
  return entries(text, key).map((entry) => entry.path);
}

describe('NATIVE_CATEGORIES', () => {
  it("are the keys of the manifest's [native] table in the SDK's schema", () => {
    const schema = /** @type {{ $defs: { NativeSection: { properties: Record<string, unknown> } } }} */ (
      /** @type {unknown} */ (readRules(root).schema)
    );

    assert.deepEqual(Object.keys(schema.$defs.NativeSection.properties).sort(), [...NATIVE_CATEGORIES]);
  });
});

describe('nativeGrants', () => {
  it("lists a manifest's grants with their reasons in a fixed order", () => {
    const grants = nativeGrants({ native: { sockets: 'Connects to workers.', processes: 'Runs git.' } });

    assert.deepEqual(grants, [
      { category: 'processes', reason: 'Runs git.' },
      { category: 'sockets', reason: 'Connects to workers.' },
    ]);
    assert.deepEqual(nativeGrants({}), []);
  });
});

describe('pluginClippyConfiguration', () => {
  it("keeps the root's settings and refuses every category that the plugin does not grant", () => {
    const text = pluginClippyConfiguration(ROOT, 'notes', []);
    const parsed = JSON.parse(JSON.stringify(parse(text)));
    const [, written] = entries(text, 'disallowed-methods');

    assert.match(text, /^# Generated by scripts\/plugins\/check-native\.mjs/u);
    assert.equal(parsed['avoid-breaking-exported-api'], false);
    assert.deepEqual(paths(text, 'disallowed-methods'), [
      'std::time::SystemTime::now',
      ...NATIVE_CALLS['file-writes'].methods,
      ...NATIVE_CALLS.processes.methods,
      ...NATIVE_CALLS.sockets.methods,
    ]);
    assert.deepEqual(paths(text, 'disallowed-types'), [
      ...NATIVE_CALLS['file-writes'].types,
      ...NATIVE_CALLS.processes.types,
      ...NATIVE_CALLS.sockets.types,
    ]);
    assert.equal(
      written?.reason,
      "The manifest of notes does not grant file-writes under [native]: a plugin's library crates reach the system through the SDK's services (ADR-0035, decision 6).",
    );
  });

  it('leaves out the calls of a category that the plugin grants', () => {
    const text = pluginClippyConfiguration(ROOT, 'workers', ['sockets']);

    assert.ok(!paths(text, 'disallowed-types').includes('tokio::net::TcpStream'));
    assert.ok(!paths(text, 'disallowed-types').includes('tonic::transport::Endpoint'));
    assert.ok(paths(text, 'disallowed-types').includes('std::process::Command'));
    assert.ok(paths(text, 'disallowed-methods').includes('std::fs::write'));
  });

  it("lets Clippy skip only the paths that a crate or a target may not have, so it reports a typo in std's", () => {
    const text = pluginClippyConfiguration(ROOT, 'notes', []);
    const written = [...entries(text, 'disallowed-methods'), ...entries(text, 'disallowed-types')].slice(1);
    const skippable = written.filter((entry) => entry['allow-invalid'] === true).map((entry) => entry.path);
    const checked = written.filter((entry) => entry['allow-invalid'] === false).map((entry) => entry.path);

    assert.equal(skippable.length + checked.length, written.length);
    assert.ok(checked.includes('std::fs::write') && checked.includes('std::net::TcpStream'));
    assert.ok(skippable.includes('std::os::unix::fs::symlink') && skippable.includes('tokio::fs::write'));
    assert.ok(checked.every((path) => path.startsWith('std::') && !path.startsWith('std::os::')));
  });
});

describe('codeOf', () => {
  it('blanks comments and the contents of literals and keeps the lines', () => {
    const source = [
      '// #[allow(warnings)]',
      `let quote = '"'; let text = "a \\" b"; let raw = r#"say "hi""#;`,
      `fn first<'a>(x: &'a str) -> &'a str { x } /* one /* nested */ */`,
    ].join('\n');

    const code = codeOf(source);

    assert.equal(code.split('\n').length, 3);
    assert.equal(code.length, source.length);
    assert.doesNotMatch(code, /allow|hi|nested|a \\" b/u);
    assert.match(code, /fn first<'a>\(x: &'a str\) -> &'a str \{ x \}/u);
  });
});

describe('nativeSuppressions', () => {
  it('finds allow and expect attributes that name a lint of the rule or a group that holds it', () => {
    const source = [
      '#[expect(clippy::disallowed_methods, reason = "wraps (once) the clock")]',
      'fn clock() {}',
      '#[cfg_attr(all(test, unix), allow(clippy::all, dead_code))]',
      'mod checks {}',
      '#![expect(',
      '    clippy::disallowed_types,',
      '    reason = "the link"',
      ')]',
      '#[allow(warnings)] #[expect(clippy::style, reason = "x")] fn other() {}',
    ].join('\n');

    assert.deepEqual(nativeSuppressions(source), [
      { line: 1, lint: 'clippy::disallowed_methods' },
      { line: 3, lint: 'clippy::all' },
      { line: 5, lint: 'clippy::disallowed_types' },
      { line: 9, lint: 'warnings' },
      { line: 9, lint: 'clippy::style' },
    ]);
  });

  it('ignores other lints, comments, doc comments, strings and calls of expect', () => {
    const source = [
      '//! An example: #[expect(clippy::disallowed_methods)]',
      '/// #[allow(clippy::all)]',
      '#[expect(clippy::too_many_lines, reason = "clippy::all of it")]',
      'fn long() { let text = "#[allow(warnings)]"; value.expect("warnings"); }',
      '/* #[allow(clippy::disallowed_types)] */',
    ].join('\n');

    assert.deepEqual(nativeSuppressions(source), []);
  });
});
