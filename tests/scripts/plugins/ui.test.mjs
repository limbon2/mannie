// @ts-check
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { after, describe, it } from 'node:test';

import { messageBarrel, uiPluginList, uiPluginLists, uiPlugins } from '../../../scripts/plugins/lib/ui.mjs';

/** @type {import('../../../scripts/plugins/lib/ui.mjs').UiPlugin[]} */
const PLUGINS = [
  { folder: 'plugins/workers', hasUi: true, id: 'workers', validation: false },
  { folder: 'plugins/log-viewer', hasUi: false, id: 'log-viewer', validation: false },
  { folder: 'tests/fixtures/plugins/example', hasUi: true, id: 'example', validation: true },
];

describe('uiPlugins', () => {
  const root = mkdtempSync(join(tmpdir(), 'mannie-ui-'));
  after(() => rmSync(root, { force: true, recursive: true }));

  it('tells a plugin with ui/index.ts from one without', () => {
    mkdirSync(join(root, 'plugins', 'workers', 'ui'), { recursive: true });
    writeFileSync(join(root, 'plugins', 'workers', 'ui', 'index.ts'), 'export default {};\n');
    mkdirSync(join(root, 'plugins', 'log-viewer', 'ui', 'generated'), { recursive: true });

    const plugins = uiPlugins(root, [
      { folder: 'plugins/workers', id: 'workers', validation: false },
      { folder: 'plugins/log-viewer', id: 'log-viewer', validation: false },
    ]);

    assert.deepEqual(
      plugins.map((plugin) => [plugin.id, plugin.hasUi]),
      [
        ['workers', true],
        ['log-viewer', false],
      ],
    );
  });
});

describe('uiPluginList', () => {
  it('imports each definition and names every plugin from the catalog, a plugin without UI included', () => {
    const text = uiPluginList(PLUGINS.slice(0, 2), 'The plugins.');

    assert.match(text, /^\/\/ Generated by `task gen`/);
    assert.ok(text.includes("import workersPlugin from '../../../../../plugins/workers/ui/index.js';\n"), text);
    assert.ok(!text.includes('log-viewer/ui/index.js'), text);
    assert.ok(
      text.includes(
        "  {\n    definition: workersPlugin,\n    description: m.workers_plugin_description,\n    id: 'workers',\n    name: m.workers_plugin_name,\n  },\n",
      ),
      text,
    );
    assert.ok(
      text.includes(
        "  {\n    definition: null,\n    description: m.log_viewer_plugin_description,\n    id: 'log-viewer',\n    name: m.log_viewer_plugin_name,\n  },\n",
      ),
      text,
    );
  });

  it('keeps the order of the starts', () => {
    const text = uiPluginList([...PLUGINS].reverse(), 'The plugins.');

    assert.ok(text.indexOf("id: 'example'") < text.indexOf("id: 'log-viewer'"), text);
    assert.ok(text.indexOf("id: 'log-viewer'") < text.indexOf("id: 'workers'"), text);
  });
});

describe('uiPluginLists', () => {
  it('leaves the fixture plugins out of the list of the builds that ship', () => {
    const [shipped, validation] = uiPluginLists(PLUGINS);

    assert.equal(shipped?.path, 'apps/desktop/src/lib/generated/plugin-list.ts');
    assert.equal(validation?.path, 'apps/desktop/src/lib/generated/plugin-list.validation.ts');
    assert.ok(!String(shipped?.text).includes('example'), shipped?.text);
    assert.ok(
      String(validation?.text).includes(
        "import examplePlugin from '../../../../../tests/fixtures/plugins/example/ui/index.js';",
      ),
      validation?.text,
    );
  });
});

describe('messageBarrel', () => {
  it("re-exports the plugin's keys from the compiled catalog, sorted, as `m`", () => {
    const [messages, list] = messageBarrel('plugins/log-viewer', ['log_viewer_plugin_name', 'log_viewer_open']);

    assert.equal(messages?.path, 'plugins/log-viewer/ui/generated/messages.ts');
    assert.ok(String(messages?.text).endsWith("export * as m from './message-list.js';\n"), messages?.text);
    assert.equal(list?.path, 'plugins/log-viewer/ui/generated/message-list.ts');
    assert.ok(
      String(list?.text).endsWith(
        "export {\n  log_viewer_open,\n  log_viewer_plugin_name,\n} from '../../../../apps/desktop/src/lib/paraglide/messages.js';\n",
      ),
      list?.text,
    );
  });

  it("reaches the compiled catalog from a fixture plugin's folder", () => {
    const [, list] = messageBarrel('tests/fixtures/plugins/example', ['example_plugin_name']);

    assert.ok(
      String(list?.text).includes("from '../../../../../../apps/desktop/src/lib/paraglide/messages.js'"),
      list?.text,
    );
  });

  it('exports nothing for a plugin without messages', () => {
    const [, list] = messageBarrel('plugins/quiet', []);

    assert.ok(String(list?.text).endsWith('\nexport {};\n'), list?.text);
  });
});
