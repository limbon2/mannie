// @ts-check
// The files of the launcher, `.generated/desktop/` (ADR-0035, decision 4):
// its workspace manifest, the crate `mannie-plugin-list`, which returns the
// plugins in the order of their starts, and the program
// `mannie-plugin-bindings`, which writes each plugin's bindings and the
// interfaces that the desktop binary's build script grants (ADR-0034,
// decisions 8 and 9). Each function returns text, so the generator compares
// it with what is on disk before it writes, and the tests read it.

import { posix } from 'node:path';

import { compareText } from './manifests.mjs';

/**
 * A plugin of the launcher.
 * @typedef {object} LauncherPlugin
 * @property {string} crateFolder its entry crate's folder, relative to the root, with forward slashes
 * @property {string} entry its entry crate's package name
 * @property {string} folder its folder, relative to the root, with forward slashes
 * @property {string} id
 * @property {boolean} validation whether only validation builds bundle it
 */

/** The first lines of every generated file, in a comment of its language. */
const GENERATED = [
  "Generated by `task gen` (scripts/plugins/generate.mjs) from the plugins'",
  'manifests (ADR-0035, decisions 3 and 4). Do not edit or commit it.',
];

/**
 * A TOML key, bare where TOML allows it.
 * @param {string} key
 */
function tomlKey(key) {
  return /^[A-Za-z0-9_-]+$/u.test(key) ? key : JSON.stringify(key);
}

/**
 * A TOML value on one line: strings, numbers, booleans, arrays and inline
 * tables. JSON's string escapes are valid in TOML's basic strings.
 * @param {unknown} value
 * @returns {string}
 */
export function tomlValue(value) {
  if (Array.isArray(value)) {
    return `[${value.map(tomlValue).join(', ')}]`;
  }
  const isTable = typeof value === 'object' && value !== null;
  if (isTable) {
    const fields = Object.entries(value).map(([key, field]) => `${tomlKey(key)} = ${tomlValue(field)}`);
    return `{ ${fields.join(', ')} }`;
  }
  if (typeof value === 'string') {
    return JSON.stringify(value);
  }
  return String(value);
}

/**
 * A TOML table with one line for each key.
 * @param {string} header such as `workspace.package`
 * @param {Record<string, unknown>} table
 */
function tomlTable(header, table) {
  const lines = Object.entries(table).map(([key, value]) => `${tomlKey(key)} = ${tomlValue(value)}`);
  return `[${header}]\n${lines.join('\n')}\n`;
}

/**
 * The path from the launcher's folder to a folder of the repository.
 * @param {string} launcherFolder relative to the root
 * @param {string} folder relative to the root
 */
function fromLauncher(launcherFolder, folder) {
  return posix.relative(launcherFolder, folder);
}

/**
 * The launcher's `Cargo.toml`: its members, the root's package settings,
 * the root's dependencies with their paths rebased, the desktop's two crates,
 * the generated crates and each plugin's entry crate, and the root's lints
 * and profiles, so that the launcher builds the desktop app as the root
 * would.
 * @param {object} options
 * @param {string} options.binaryFolder the desktop binary's folder, relative to the root
 * @param {string} options.coreFolder the folder of `mannie-desktop-core`, relative to the root
 * @param {string} options.launcherFolder relative to the root
 * @param {LauncherPlugin[]} options.plugins in the order of their starts
 * @param {Record<string, any>} options.rootManifest the root's `Cargo.toml`, parsed
 */
export function launcherManifest({ binaryFolder, coreFolder, launcherFolder, plugins, rootManifest }) {
  const workspace = rootManifest.workspace;
  /** @type {Record<string, unknown>} */
  const dependencies = {};
  for (const [name, dependency] of Object.entries(workspace.dependencies ?? {})) {
    const hasPath = typeof dependency === 'object' && typeof dependency.path === 'string';
    dependencies[name] = hasPath ? { ...dependency, path: fromLauncher(launcherFolder, dependency.path) } : dependency;
  }
  dependencies['mannie-desktop-core'] = { path: fromLauncher(launcherFolder, coreFolder) };
  dependencies['mannie-plugin-list'] = { path: 'plugin-list' };
  for (const plugin of plugins) {
    dependencies[plugin.entry] = { path: fromLauncher(launcherFolder, plugin.crateFolder) };
  }
  const sortedDependencies = Object.fromEntries(Object.entries(dependencies).sort(([a], [b]) => compareText(a, b)));
  const members = [fromLauncher(launcherFolder, binaryFolder), 'plugin-bindings', 'plugin-list'];
  const sections = [
    GENERATED.map((line) => `# ${line}`).join('\n'),
    tomlTable('workspace', { members, resolver: workspace.resolver ?? '3' }),
    tomlTable('workspace.package', workspace.package ?? {}),
    tomlTable('workspace.dependencies', sortedDependencies),
  ];
  for (const [tool, lints] of Object.entries(workspace.lints ?? {})) {
    sections.push(tomlTable(`workspace.lints.${tomlKey(tool)}`, lints));
  }
  for (const [profile, settings] of Object.entries(rootManifest.profile ?? {})) {
    sections.push(tomlTable(`profile.${tomlKey(profile)}`, settings));
  }
  return `${sections.join('\n')}`;
}

/**
 * The package table of a generated crate, which inherits the workspace's
 * settings.
 * @param {string} name
 * @param {string} description
 */
function generatedPackage(name, description) {
  return `${GENERATED.map((line) => `# ${line}`).join('\n')}
[package]
name = "${name}"
version.workspace = true
edition.workspace = true
rust-version.workspace = true
description = ${JSON.stringify(description)}
license.workspace = true
publish.workspace = true
`;
}

/**
 * The Rust path of a crate's library, such as `mannie_workers`.
 * @param {string} entry the package's name
 */
function crateName(entry) {
  return entry.replaceAll('-', '_');
}

/**
 * The dependencies of a generated crate on the plugins' entry crates, those
 * of fixture plugins optional.
 * @param {LauncherPlugin[]} plugins
 */
function entryDependencies(plugins) {
  return plugins
    .map((plugin) => {
      const optional = plugin.validation ? ', optional = true' : '';
      return `${plugin.entry} = { workspace = true${optional} }`;
    })
    .sort();
}

/**
 * The list of plugins as a Rust expression, one entry on each line.
 * @param {LauncherPlugin[]} plugins
 * @param {string} indent
 */
function rustPluginVec(plugins, indent) {
  const entries = plugins.map((plugin) => `${indent}    ${crateName(plugin.entry)}::mannie_plugin(),`);
  return `${indent}vec![\n${entries.join('\n')}\n${indent}]`;
}

/**
 * The crate `mannie-plugin-list`: `plugins()` returns the bundled plugins in
 * the order of their starts, with the fixture plugins only under the feature
 * `validation`, which the desktop binary's own feature turns on.
 * @param {LauncherPlugin[]} plugins in the order of their starts
 * @returns {{ cargoToml: string, libRs: string }}
 */
export function pluginListCrate(plugins) {
  const fixtures = plugins.filter((plugin) => plugin.validation);
  const shipped = plugins.filter((plugin) => !plugin.validation);
  const validationFeature = fixtures.map((plugin) => `"dep:${plugin.entry}"`).join(', ');
  const cargoToml = `${generatedPackage(
    'mannie-plugin-list',
    'The plugins in plugins/*/plugin.toml when `task gen` ran, in the order of their starts, with the fixture plugins of tests/fixtures/plugins/ in validation builds (ADR-0035).',
  )}
[dependencies]
${[...entryDependencies(plugins), 'mannie-plugin-sdk = { workspace = true }'].sort().join('\n')}

[features]
# The fixture plugins, which only validation builds bundle (ADR-0035,
# decision 9).
validation = [${validationFeature}]

[lints]
workspace = true
`;
  const header = `${GENERATED.map((line) => `//! ${line}`).join('\n')}
//!
//! The plugins in \`plugins/*/plugin.toml\`, in the order of their starts, and
//! in validation builds also the fixture plugins of \`tests/fixtures/plugins/\`.

use mannie_plugin_sdk::plugin::PluginEntry;
`;
  if (fixtures.length === 0) {
    return {
      cargoToml,
      libRs: `${header}
/// The plugins that this build bundles, in the order of their starts.
pub fn plugins() -> Vec<PluginEntry> {
${rustPluginVec(shipped, '    ')}
}
`,
    };
  }
  return {
    cargoToml,
    libRs: `${header}
/// The plugins that this build bundles, in the order of their starts.
#[cfg(not(feature = "validation"))]
pub fn plugins() -> Vec<PluginEntry> {
${rustPluginVec(shipped, '    ')}
}

/// The plugins that this validation build bundles, with the fixture plugins,
/// in the order of their starts.
#[cfg(feature = "validation")]
pub fn plugins() -> Vec<PluginEntry> {
${rustPluginVec(plugins, '    ')}
}
`,
  };
}

/**
 * The program `mannie-plugin-bindings`, which `task gen` runs after it
 * wrote the launcher: for every plugin, also the fixture plugins, it checks
 * the manifest that the entry crate embeds as the host does, writes the
 * plugin's TypeScript bindings into `ui/generated/` of its folder and adds
 * its commands and channels to `interfaces.json` in the launcher's folder,
 * which the desktop binary's build script grants.
 * @param {LauncherPlugin[]} plugins in the order of their starts
 * @returns {{ cargoToml: string, mainRs: string }}
 */
export function pluginBindingsCrate(plugins) {
  const cargoToml = `${generatedPackage(
    'mannie-plugin-bindings',
    "Writes each plugin's TypeScript bindings into ui/generated/ of its folder and the plugins' interfaces into .generated/desktop/interfaces.json (ADR-0034, ADR-0035).",
  )}
[[bin]]
name = "mannie-plugin-bindings"
path = "src/main.rs"

[dependencies]
${[
  ...plugins.map((plugin) => `${plugin.entry} = { workspace = true }`),
  'mannie-plugin-sdk = { workspace = true, features = ["bindings", "manifest"] }',
  'serde_json = { workspace = true }',
]
  .sort()
  .join('\n')}

[lints]
workspace = true
`;
  const bundled = plugins.map(
    (plugin) => `        Bundled {
            folder: ${JSON.stringify(plugin.folder)},
            validation: ${String(plugin.validation)},
            entry: ${crateName(plugin.entry)}::mannie_plugin(),
        },`,
  );
  const mainRs = `${GENERATED.map((line) => `//! ${line}`).join('\n')}
//!
//! Writes each plugin's TypeScript bindings into \`ui/generated/\` of its
//! folder, and the plugins' commands and channels into \`interfaces.json\` in
//! the launcher's folder, which the desktop binary's build script grants
//! (ADR-0034, decisions 8 and 9). \`task gen\` runs it.

use std::fs;
use std::path::{Path, PathBuf};

use mannie_plugin_sdk::bindings::export_plugin;
use mannie_plugin_sdk::manifest::Manifest;
use mannie_plugin_sdk::plugin::PluginEntry;
use serde_json::json;

/// A plugin with its folder, relative to the repository's root, and whether
/// only validation builds bundle it.
struct Bundled {
    folder: &'static str,
    validation: bool,
    entry: PluginEntry,
}

/// Every plugin of the launcher, in the order of their starts.
fn bundled() -> Vec<Bundled> {
    vec![
${bundled.join('\n')}
    ]
}

/// The repository's root, three folders above this crate.
fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..")
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = repository_root();
    let mut interfaces = Vec::new();
    for plugin in bundled() {
        let manifest = Manifest::parse(plugin.entry.manifest)
            .map_err(|error| format!("{}/plugin.toml: {error}", plugin.folder))?;
        let id = manifest.id.as_str();
        let interface = plugin.entry.plugin.interface();
        let folder = root.join(plugin.folder).join("ui/generated");
        export_plugin(id, &interface, &folder)?;
        interfaces.push(json!({
            "id": id,
            "validation": plugin.validation,
            "commands": interface.command_names(),
            "channels": interface.channel_names(),
        }));
    }
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../interfaces.json");
    let text = format!("{}\\n", serde_json::to_string_pretty(&interfaces)?);
    // The desktop binary's build script runs again when the file changes, so
    // it is written only when its content does.
    let unchanged = fs::read_to_string(&path).is_ok_and(|current| current == text);
    if !unchanged {
        fs::write(&path, text)?;
    }
    Ok(())
}
`;
  return { cargoToml, mainRs };
}

/**
 * The editor workspace, which links every Cargo workspace for rust-analyzer:
 * the root, the plugins and then the launcher, because rust-analyzer
 * analyzes a file that several workspaces share in the first one that holds
 * it (ADR-0035, decision 12).
 * @param {string} root the repository's root, absolute
 * @param {string[]} manifests every workspace's manifest, relative to the root, in that order
 */
export function editorWorkspace(root, manifests) {
  const absolute = manifests.map((manifest) => posix.join(root.replaceAll('\\', '/'), manifest));
  const workspace = {
    folders: [{ path: '..' }],
    settings: { 'rust-analyzer.linkedProjects': absolute },
  };
  return `${JSON.stringify(workspace, null, 2)}\n`;
}
