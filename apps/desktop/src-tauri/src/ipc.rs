/// The commands of every build.
#[expect(
    trivial_casts,
    reason = "collect_commands! casts each command to a function pointer for specta"
)]
fn app_builder() -> Builder<Wry> {
    Builder::new()
        .error_handling(ErrorHandlingMode::Result)
        .commands(app_commands![])
}

/// The validation commands (V1, V2, V3).
#[cfg(feature = "validation")]
#[expect(
    trivial_casts,
    reason = "collect_commands! casts each command to a function pointer for specta"
)]
fn validation_builder() -> Builder<Wry> {
    Builder::new()
        .error_handling(ErrorHandlingMode::Result)
        .commands(collect_commands![
            crate::commands::validation::stream_validation_events,
            crate::commands::validation::validation_ungranted_command,
            crate::commands::validation::validation_close_main_window,
            crate::commands::validation::validation_window_state,
            crate::commands::validation::validation_tray_menu,
            crate::commands::validation::validation_process_id,
            crate::commands::validation::validation_seed_conversation,
            crate::commands::validation::validation_opened_links,
            crate::commands::validation::validation_set_folder_choice,
        ])
}

/// The commands the app answers: the app commands and, in validation builds,
/// the validation commands.
#[cfg_attr(
    feature = "validation",
    expect(
        trivial_casts,
        reason = "collect_commands! casts each command to a function pointer for specta"
    )
)]
pub(crate) fn runtime_builder() -> Builder<Wry> {
    #[cfg(not(feature = "validation"))]
    {
        app_builder()
    }
    #[cfg(feature = "validation")]
    {
        Builder::new()
            .error_handling(ErrorHandlingMode::Result)
            .commands(app_commands![
                crate::commands::validation::stream_validation_events,
                crate::commands::validation::validation_ungranted_command,
                crate::commands::validation::validation_close_main_window,
                crate::commands::validation::validation_window_state,
                crate::commands::validation::validation_tray_menu,
                crate::commands::validation::validation_process_id,
                crate::commands::validation::validation_seed_conversation,
                crate::commands::validation::validation_opened_links,
                crate::commands::validation::validation_set_folder_choice,
            ])
    }
}

/// Writes the TypeScript bindings into `directory`: `bindings.ts` with the app
/// commands and, in validation builds, `validation.ts` with the validation
/// commands. The folder is generated and never committed.
pub fn export_bindings(directory: &Path) -> Result<(), BindingsError> {
    fs::create_dir_all(directory).map_err(|source| BindingsError::Directory {
        path: directory.to_path_buf(),
        source,
    })?;
    export(&app_builder(), &directory.join("bindings.ts"))?;
    #[cfg(feature = "validation")]
    export(&validation_builder(), &directory.join("validation.ts"))?;
    Ok(())
}

fn export(builder: &Builder<Wry>, path: &Path) -> Result<(), BindingsError> {
    builder
        .export(Typescript::default().header(HEADER), path)
        .map_err(|source| BindingsError::Export {
            path: path.to_path_buf(),
            source: Box::new(source),
        })
}

/// The bindings folder in the source tree, which debug builds keep current.
#[cfg(debug_assertions)]
pub(crate) fn source_bindings_directory() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/generated")
}
