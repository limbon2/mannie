//! The IPC contract (ADR-0007): the commands the webview may call, registered
//! with tauri-specta so that the TypeScript bindings come from the Rust types.
//!
//! Every command also needs a permission (`build.rs`) and a grant
//! (`capabilities/`), or Tauri refuses it (ADR-0004).

pub(crate) mod channel;
pub(crate) mod subscriptions;

use std::fs;
use std::path::{Path, PathBuf};

use specta_typescript::Typescript;
use tauri::Wry;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

