//! The bindings exporter (ADR-0034, decision 9; feature `bindings`): it
//! writes a plugin's interface as TypeScript, and the envelopes and the
//! transport that every plugin's bindings use.
//!
//! [`export_plugin`] writes `bindings.ts`, with the plugin's commands,
//! channels and types, and `plugin.ts`, with its ID and constants, into the
//! plugin's `ui/generated/`. [`export_core`] writes `plugin-sdk.ts`, the
//! envelopes, and `plugin-transport.ts`, the one file that names the route of
//! plugin calls, into the core's generated folder. None of the files is
//! committed (ADR-0007).
//!
//! The types follow serde's attributes in both directions, as tauri-specta
//! exports the core's bindings, so a plugin's types read the same in its
//! file as they did in the core's. The exporter writes the text of
//! `PluginFailure<E>` itself, because specta-serde refuses a generic payload
//! in an enum tagged by `origin` (spike S5). It refuses a plugin error that
//! is not an enum tagged by `code`, or that uses a host code, so the UI
//! tells the host's refusals from the plugin's errors by their code alone.

use std::borrow::Cow;
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use specta::datatype::{DataType, Fields, Reference};
use specta::{Format as _, Type, Types};
use specta_serde::Phase;
use specta_typescript::{Exporter, FrameworkExporter, Typescript};

use crate::contracts::{ChannelBatch, CommandError, SubscriptionEnd, SubscriptionId};
use crate::ipc::{ChannelMessage, Endpoint, HostRefusal, Interface};

/// The first line of every file that the exporter writes.
const HEADER: &str = "// Generated by `task gen` from the plugins' Rust interfaces (ADR-0034, decision 9). Do not edit or commit it.";

/// The name under which a plugin's bindings import the SDK's types. A
/// plugin type with this name would clash with the import.
const SDK_NAMESPACE: &str = "sdk";

/// Why the bindings could not be written.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum ExportError {
    /// A plugin's error uses a code of the host's refusals, so the UI could
    /// not tell the two apart.
    #[error(
        "the plugin {plugin}: the error {error} of `{endpoint}` uses the host's codes {codes:?}; the host answers them for every plugin, so rename the variants"
    )]
    HostCode {
        /// The plugin's ID.
        plugin: String,
        /// The command or channel.
        endpoint: &'static str,
        /// The error's Rust name.
        error: &'static str,
        /// The codes that the host uses.
        codes: Vec<String>,
    },
    /// A plugin's error is not an enum tagged by `code`.
    #[error(
        "the plugin {plugin}: the error {error} of `{endpoint}` is not an enum with #[serde(tag = \"code\")]: {reason}"
    )]
    NotCoded {
        /// The plugin's ID.
        plugin: String,
        /// The command or channel.
        endpoint: &'static str,
        /// The error's Rust name.
        error: &'static str,
        /// What the exporter found instead.
        reason: String,
    },
    /// A plugin's type has a name that the generated file needs.
    #[error("the plugin {plugin}: the type {name} has a name that the bindings reserve")]
    ReservedName {
        /// The plugin's ID.
        plugin: String,
        /// The type's name.
        name: String,
    },
    /// serde's attributes could not be applied to the types.
    #[error("the types could not be formatted: {0}")]
    Format(String),
    /// specta-typescript refused the types.
    #[error("the TypeScript could not be written to {path}")]
    Typescript {
        /// The file.
        path: PathBuf,
        /// The cause, boxed because the exporter's error is large.
        #[source]
        source: Box<specta_typescript::Error>,
    },
    /// A folder could not be created.
    #[error("could not create the folder {path}")]
    Directory {
        /// The folder.
        path: PathBuf,
        /// The cause.
        #[source]
        source: std::io::Error,
    },
}

/// The types after serde's attributes, in both directions.
fn format_types(types: &Types) -> Result<Types, ExportError> {
    specta_serde::PhasesFormat
        .map_types(types)
        .map(Cow::into_owned)
        .map_err(|error| ExportError::Format(error.to_string()))
}

/// The value of the `code` tag of every variant of an error, after serde's
/// renames, read from specta's view of the type, so no list of codes is
/// written twice.
fn error_codes(error: &DataType, formatted: &Types) -> Result<Vec<String>, String> {
    let selected = specta_serde::select_phase_datatype(error, formatted, Phase::Serialize);
    let DataType::Reference(Reference::Named(reference)) = &selected else {
        return Err("it is not a named type".to_owned());
    };
    let named = formatted
        .get(reference)
        .ok_or_else(|| "its definition is missing".to_owned())?;
    let Some(DataType::Enum(definition)) = &named.ty else {
        return Err("it is not an enum".to_owned());
    };
    let mut codes = Vec::with_capacity(definition.variants.len());
    for (variant_name, variant) in &definition.variants {
        let code = tag_value(&variant.fields, "code")
            .ok_or_else(|| format!("the variant {variant_name} has no `code` tag"))?;
        codes.push(code);
    }
    Ok(codes)
}

/// The string literal of the tag field `tag` among `fields`, after
/// specta-serde merged an internally tagged variant into an object.
fn tag_value(fields: &Fields, tag: &str) -> Option<String> {
    match fields {
        Fields::Named(named) => named.fields.iter().find_map(|(name, field)| {
            if name != tag {
                return None;
            }
            match &field.ty {
                Some(DataType::Enum(literal)) if literal.variants.len() == 1 => literal
                    .variants
                    .first()
                    .map(|(value, _variant)| value.to_string()),
                _other => None,
            }
        }),
        Fields::Unnamed(unnamed) => unnamed.fields.iter().find_map(|field| match &field.ty {
            Some(DataType::Intersection(parts)) => parts.iter().find_map(|part| match part {
                DataType::Struct(object) => tag_value(&object.fields, tag),
                _other => None,
            }),
            _other => None,
        }),
        Fields::Unit => None,
    }
}

/// The host's codes, read from the TypeScript shape of [`HostRefusal`].
pub fn host_codes() -> Result<Vec<String>, ExportError> {
    let mut types = Types::default();
    let refusal = HostRefusal::definition(&mut types);
    let formatted = format_types(&types)?;
    error_codes(&refusal, &formatted).map_err(|reason| ExportError::NotCoded {
        plugin: "host".to_owned(),
        endpoint: "",
        error: std::any::type_name::<HostRefusal>(),
        reason,
    })
}

/// The types that an interface's endpoints and constants name, and the
/// shape of each endpoint's input, output and error.
struct Collected {
    types: Types,
    commands: Vec<Shapes>,
    channels: Vec<Shapes>,
}

/// One endpoint with its types.
#[derive(Clone)]
struct Shapes {
    name: &'static str,
    docs: &'static str,
    error_name: &'static str,
    input: DataType,
    output: DataType,
    error: DataType,
}

fn shapes(endpoint: &Endpoint, types: &mut Types) -> Shapes {
    Shapes {
        name: endpoint.name,
        docs: endpoint.docs,
        error_name: endpoint.error_name,
        input: (endpoint.input)(types),
        output: (endpoint.output)(types),
        error: (endpoint.error)(types),
    }
}

fn collect(interface: &Interface) -> Collected {
    let mut types = Types::default();
    let commands = interface
        .commands()
        .iter()
        .map(|endpoint| shapes(endpoint, &mut types))
        .collect();
    let channels = interface
        .channels()
        .iter()
        .map(|endpoint| shapes(endpoint, &mut types))
        .collect();
    Collected {
        types,
        commands,
        channels,
    }
}

/// Checks every error of the interface: it is tagged by `code`, and none of
/// its codes is a host code. No type of the plugin is named like the
/// bindings' import of the SDK.
pub fn check_interface(plugin: &str, interface: &Interface) -> Result<(), ExportError> {
    let collected = collect(interface);
    let formatted = format_types(&collected.types)?;
    let host: BTreeSet<String> = host_codes()?.into_iter().collect();
    for endpoint in collected.commands.iter().chain(&collected.channels) {
        let codes =
            error_codes(&endpoint.error, &formatted).map_err(|reason| ExportError::NotCoded {
                plugin: plugin.to_owned(),
                endpoint: endpoint.name,
                error: endpoint.error_name,
                reason,
            })?;
        let clashes: Vec<String> = codes
            .into_iter()
            .filter(|code| host.contains(code))
            .collect();
        if !clashes.is_empty() {
            return Err(ExportError::HostCode {
                plugin: plugin.to_owned(),
                endpoint: endpoint.name,
                error: endpoint.error_name,
                codes: clashes,
            });
        }
    }
    if let Some(named) = formatted
        .into_unsorted_iter()
        .find(|named| named.name == SDK_NAMESPACE)
    {
        return Err(ExportError::ReservedName {
            plugin: plugin.to_owned(),
            name: named.name.to_string(),
        });
    }
    Ok(())
}

fn render(
    exporter: &FrameworkExporter<'_>,
    shape: &DataType,
    phase: Phase,
) -> Result<String, specta_typescript::Error> {
    let selected = specta_serde::select_phase_datatype(shape, exporter.types, phase);
    match &selected {
        DataType::Reference(reference) => exporter.reference(reference),
        other => exporter.inline(other),
    }
}

fn is_unit(shape: &DataType) -> bool {
    matches!(shape, DataType::Tuple(tuple) if tuple.elements.is_empty())
}

/// `snake_case` as `lowerCamelCase`, the name of a generated function.
fn lower_camel_case(snake: &str) -> String {
    let mut out = String::with_capacity(snake.len());
    let mut upper = false;
    for character in snake.chars() {
        if character == '_' {
            upper = true;
        } else if upper {
            out.extend(character.to_uppercase());
            upper = false;
        } else {
            out.push(character);
        }
    }
    out
}

/// A documentation comment of one line for TypeScript, or nothing for
/// empty documentation.
fn doc_comment(docs: &str, indent: &str) -> String {
    if docs.is_empty() {
        return String::new();
    }
    format!("{indent}/** {docs} */\n")
}

/// A JavaScript string literal, as JSON writes it.
fn string_literal(text: &str) -> String {
    serde_json::Value::String(text.to_owned()).to_string()
}

fn exporter(
    runtime: impl Fn(FrameworkExporter<'_>) -> Result<Cow<'static, str>, specta_typescript::Error>
    + Send
    + Sync
    + 'static,
) -> Exporter {
    Exporter::from(Typescript::default().header(HEADER))
        .framework_prelude("")
        .framework_runtime(runtime)
}

fn create_directory(folder: &Path) -> Result<(), ExportError> {
    fs::create_dir_all(folder).map_err(|source| ExportError::Directory {
        path: folder.to_path_buf(),
        source,
    })
}

fn export_to(exporter: &Exporter, path: &Path, types: &Types) -> Result<(), ExportError> {
    exporter
        .export_to(path, types, specta_serde::PhasesFormat)
        .map_err(|source| ExportError::Typescript {
            path: path.to_path_buf(),
            source: Box::new(source),
        })
}

/// The commands and channels of `bindings.ts`.
fn plugin_runtime(
    plugin: &str,
    commands: &[Shapes],
    channels: &[Shapes],
    exporter: &FrameworkExporter<'_>,
) -> Result<String, specta_typescript::Error> {
    let mut out = String::new();
    if !channels.is_empty() {
        writeln!(
            out,
            "import type * as {SDK_NAMESPACE} from '@mannie/plugin-sdk/ipc';"
        )
        .expect("writing to a String cannot fail");
    }
    out.push_str("import { pluginTransport } from '@mannie/plugin-sdk/transport';\n\n");
    writeln!(
        out,
        "const transport = pluginTransport({});\n",
        string_literal(plugin)
    )
    .expect("writing to a String cannot fail");

    out.push_str("/** The plugin's commands. */\nexport const commands = {\n");
    for command in commands {
        out.push_str(&doc_comment(command.docs, "\t"));
        let output = render(exporter, &command.output, Phase::Serialize)?;
        let error = render(exporter, &command.error, Phase::Serialize)?;
        let function = lower_camel_case(command.name);
        let name = string_literal(command.name);
        if is_unit(&command.input) {
            writeln!(
                out,
                "\t{function}: () => transport.call<{output}, {error}>({name}, null),"
            )
            .expect("writing to a String cannot fail");
        } else {
            let input = render(exporter, &command.input, Phase::Deserialize)?;
            writeln!(
                out,
                "\t{function}: (input: {input}) => transport.call<{output}, {error}>({name}, input),"
            )
        .expect("writing to a String cannot fail");
        }
    }
    out.push_str("};\n\n");

    out.push_str("/** The plugin's channels. */\nexport const channels = {\n");
    for channel in channels {
        out.push_str(&doc_comment(channel.docs, "\t"));
        let item = render(exporter, &channel.output, Phase::Serialize)?;
        let error = render(exporter, &channel.error, Phase::Serialize)?;
        let function = lower_camel_case(channel.name);
        let name = string_literal(channel.name);
        let on = format!(
            "on: {SDK_NAMESPACE}.Channel<{SDK_NAMESPACE}.ChannelBatch<{SDK_NAMESPACE}.ChannelMessage<{item}>>>"
        );
        if is_unit(&channel.input) {
            writeln!(
                out,
                "\t{function}: ({on}) => transport.subscribe<{item}, {error}>({name}, null, on),"
            )
            .expect("writing to a String cannot fail");
        } else {
            let input = render(exporter, &channel.input, Phase::Deserialize)?;
            writeln!(
                out,
                "\t{function}: (input: {input}, {on}) => transport.subscribe<{item}, {error}>({name}, input, on),"
            )
        .expect("writing to a String cannot fail");
        }
    }
    out.push_str(
        "};
",
    );
    Ok(out)
}

/// Writes the bindings of the plugin `plugin` into `folder`, its
/// `ui/generated/`: `bindings.ts` with its commands, channels and types, and
/// `plugin.ts` with its ID and constants. The interface passes the checks of
/// [`check_interface`] first.
pub fn export_plugin(
    plugin: &str,
    interface: &Interface,
    folder: &Path,
) -> Result<(), ExportError> {
    check_interface(plugin, interface)?;
    create_directory(folder)?;

    let collected = collect(interface);
    let id = plugin.to_owned();
    let commands = collected.commands.clone();
    let channels = collected.channels.clone();
    let bindings = exporter(move |exporter| {
        plugin_runtime(&id, &commands, &channels, &exporter).map(Cow::Owned)
    });
    export_to(&bindings, &folder.join("bindings.ts"), &collected.types)?;

    let id = plugin.to_owned();
    let constants = interface.constants().to_vec();
    let mut constant_types = Types::default();
    let shapes: Vec<DataType> = constants
        .iter()
        .map(|constant| (constant.shape)(&mut constant_types))
        .collect();
    let constants_file = exporter(move |exporter| {
        let mut out = String::new();
        writeln!(
            out,
            "/** The plugin's ID. */\nexport const PLUGIN_ID = {};",
            string_literal(&id)
        )
        .expect("writing to a String cannot fail");
        for (constant, shape) in constants.iter().zip(&shapes) {
            let ty = render(&exporter, shape, Phase::Serialize)?;
            out.push_str(&doc_comment(constant.docs, ""));
            writeln!(
                out,
                "export const {}: {ty} = {};",
                constant.name, constant.value
            )
            .expect("writing to a String cannot fail");
        }
        Ok(Cow::Owned(out))
    });
    export_to(&constants_file, &folder.join("plugin.ts"), &constant_types)
}

/// Writes the envelopes, `plugin-sdk.ts`, and the transport,
/// `plugin-transport.ts`, into `folder`, the core's generated folder.
pub fn export_core(folder: &Path) -> Result<(), ExportError> {
    create_directory(folder)?;
    let mut types = Types::default();
    HostRefusal::definition(&mut types);
    ChannelMessage::<()>::definition(&mut types);
    ChannelBatch::<()>::definition(&mut types);
    CommandError::<()>::definition(&mut types);
    SubscriptionId::definition(&mut types);
    SubscriptionEnd::definition(&mut types);

    let envelopes = exporter(|_exporter| Ok(Cow::Borrowed(PLUGIN_SDK_RUNTIME)));
    export_to(&envelopes, &folder.join("plugin-sdk.ts"), &types)?;

    let transport = exporter(|_exporter| Ok(Cow::Borrowed(PLUGIN_TRANSPORT_RUNTIME)));
    export_to(
        &transport,
        &folder.join("plugin-transport.ts"),
        &Types::default(),
    )
}

/// The envelope that the exporter writes itself: the result of a call, and
/// the failure of a plugin's command or channel.
const PLUGIN_SDK_RUNTIME: &str = "/** A call's result: the shape that `call()` in `utils/calls.ts` reads. */
export type Result<T, E> = { status: 'ok'; data: T } | { status: 'error'; error: E };

/**
 * Why a plugin's command or channel failed: a refusal of the host, which
 * answers it the same way for every plugin, or the plugin's own error. Both
 * carry a `code`, and no plugin code equals a host code, which `task gen`
 * checks.
 */
export type PluginFailure<E extends { code: string }> = ({ origin: 'host' } & HostRefusal) | ({ origin: 'plugin' } & E);";

/// The transport: the one file that names the route of plugin calls, so a
/// later build can route a plugin through another path without a change in
/// the plugin.
const PLUGIN_TRANSPORT_RUNTIME: &str = "import { type Channel, invoke } from '@tauri-apps/api/core';

import type { ChannelBatch, ChannelMessage, CommandError, PluginFailure, Result, SubscriptionId } from './plugin-sdk.js';

/** Carries one plugin's calls to the host. Generated bindings use it; plugin code never does. */
export interface PluginTransport {
	call<O, E extends { code: string }>(command: string, input: unknown): Promise<Result<O, CommandError<PluginFailure<E>>>>;
	subscribe<T, E extends { code: string }>(
		channel: string,
		input: unknown,
		on: Channel<ChannelBatch<ChannelMessage<T>>>,
	): Promise<Result<SubscriptionId, CommandError<PluginFailure<E>>>>;
}

/**
 * What a call rejected with: the host's refusal or the plugin's error, which
 * carry a code, or else Tauri's refusal, a plain string whose text differs
 * between builds, as `not_allowed`.
 */
function failure<E extends { code: string }>(error: unknown): CommandError<PluginFailure<E>> {
	if (typeof error === 'object' && error !== null && 'code' in error) {
		return error as CommandError<PluginFailure<E>>;
	}
	return { code: 'not_allowed', description: String(error), origin: 'host' };
}

/** The transport of one plugin: every call goes to the plugin's inlined Tauri plugin. */
export function pluginTransport(plugin: string): PluginTransport {
	return {
		async call<O, E extends { code: string }>(command: string, input: unknown): Promise<Result<O, CommandError<PluginFailure<E>>>> {
			try {
				return { status: 'ok', data: await invoke<O>(`plugin:${plugin}|${command}`, { input }) };
			} catch (error) {
				if (error instanceof Error) throw error;
				return { status: 'error', error: failure<E>(error) };
			}
		},
		async subscribe<T, E extends { code: string }>(
			channel: string,
			input: unknown,
			on: Channel<ChannelBatch<ChannelMessage<T>>>,
		): Promise<Result<SubscriptionId, CommandError<PluginFailure<E>>>> {
			try {
				return { status: 'ok', data: await invoke<SubscriptionId>(`plugin:${plugin}|${channel}`, { input, on }) };
			} catch (error) {
				if (error instanceof Error) throw error;
				return { status: 'error', error: failure<E>(error) };
			}
		},
	};
}";

